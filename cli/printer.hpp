namespace chupa {

/// Печатает значение литералами языка: [1, 2], {'a': 1}, строки в кавычках.
/// Что видишь — то и можешь набрать обратно, кроме трёх числовых исключений
/// ниже.
///
/// Печатает для человека, а не приводит к строке: str агрегаты отвергает
/// (docs/semantics.md §8.7), и это правило языка остаётся нетронутым.
///
/// Агрегат, встреченный на собственном пути печати, заменяется на {...} либо
/// [...]: самоссылка законна (§2.3) и зациклила бы наивный обход.
/// Отслеживается именно путь, а не всё виденное за печать, — один агрегат под
/// двумя именами циклом не является и печатается целиком оба раза. Дерево
/// глубже kMaxPrintDepth (cli/printer.cpp) печатается тем же способом — это
/// отдельная защита, не связанная с циклом.
///
/// **Три числовых исключения из "что видишь — то и набираешь".** Это те же
/// особые случаи Number → String (docs/semantics.md §4.3): `1/0` печатает
/// `inf`, `0/0` — `nan`, число величиной ≥ 1e21 — научную запись (`1e+21`);
/// грамматика числовых литералов не принимает ни экспоненты, ни ключевых слов
/// `inf`/`nan` (docs/grammar.md §4.6). Формат числа задаёт `CS::formatNumber`,
/// эта ветка ядро не трогает и не чинит эти три случая — только не обещает
/// большего, чем есть.
std::string printValue(const CS::Store &store, CS::Value value);

}  // namespace chupa
