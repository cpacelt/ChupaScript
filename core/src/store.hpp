namespace CS {

namespace detail {
/// Запись таблицы имён. Определена только в store.cpp: снаружи это неполный
/// тип, и раскладку таблицы не видит никто.
struct GlobalName;
}  // namespace detail

/// Хранилище значений ChupaScript.
///
/// Владеет тремя разными вещами по трём разным правилам, и путать их нельзя.
///
/// **Оснастка** — имена глобальных переменных и коробки строковых литералов.
/// Границу с хостом не пересекает никогда, без контекста смысла не имеет,
/// живёт ровно столько же. Учёта внутри неё нет, уходит разом в деструкторе.
///
/// **Арена операции** — только у временного региона и только байты: агрегатов
/// в ней не бывает. Сбрасывается целиком на границе операции.
///
/// **Коробки со счётчиком** — агрегаты и долгоживущие строки. Хранилище им не
/// владелец, а повитуха: оно их создаёт и до ближайшей границы операции
/// держит их ссылку в списке отложенного освобождения, а дальше судьбу коробки
/// решают те, кто её удержал — ячейка глобальной переменной, другая коробка
/// либо хост. Читать и менять коробку хранилище не умеет вовсе: это делают
/// свободные функции core/src/aggregate.hpp.
///
/// Срез, который этот класс отдаёт наружу — `string()`, `globalNameAt()` —
/// переживает лишь до ближайшей мутации того, откуда он взят.
///
/// Обоснование:
/// docs/superpowers/specs/2026-08-19-chupascript-memory-model-design.md
class Store {
   public:
    /// region — как адресуют нагрузку строки, созданные этим хранилищем. За
    /// жизнь хранилища не меняется: иначе уже выданные значения начали бы
    /// врать. Агрегатов не касается — они коробки всегда.
    ///
    /// keys — таблица имён полей; nullptr означает «завести свою». Временный
    /// регион получает таблицу постоянного: агрегат, собранный вычислением и
    /// попавший в глобальную переменную, не копируется, и переводить номера
    /// ключей было бы негде.
    /// deferred — общий список отложенного освобождения; nullptr означает
    /// «завести свой». Арена операции берёт список постоянного хранилища:
    /// сливаются они всё равно вместе, на одной и той же границе.
    explicit Store(Value::Region region = Value::Region::Boxed,
                   KeyTable *keys = nullptr, Deferred *deferred = nullptr);

    /// Определён в store.cpp: в заголовке типы пулов ещё неполны.
    ~Store();

    Store(const Store &) = delete;
    Store &operator=(const Store &) = delete;

    // ─── создание ───

    /// Создаёт строку. Представление зависит от региона, и это не исключение,
    /// а вся суть деления: промежуточная строка живёт в арене операции и
    /// стоит 0.22 нс, строка, которой предстоит операцию пережить, — коробка со
    /// счётчиком и стоит аллокацию.
    ///
    /// Допускает срез собственного пула — так выглядит пересборка строки из
    /// того же хранилища.
    Value makeString(std::string_view bytes);

    /// Строка коробкой, независимо от региона этого хранилища.
    ///
    /// Нужна там, где строке предстоит лечь внутрь агрегата: агрегат умеет
    /// уехать и пережить операцию, а смещение в арену — нет.
    Value materialize(std::string_view bytes);

    /// Укладывает байты строкового литерала и отдаёт его коробку.
    ///
    /// Оснастка, а не значение: литерал — часть программы, он живёт до смерти
    /// хранилища и в список отложенного освобождения не попадает. Иначе
    /// первая же граница операции забрала бы его у дерева разбора.
    detail::StringBox *internLiteral(std::string_view bytes);

    /// Создаёт пустой массив. capacity — сколько элементов выделить заранее;
    /// на длину не влияет, элементы добавляет только arrayPush.
    Value makeArray(std::uint32_t capacity = 0);

    /// Создаёт пустой объект. capacity — сколько пар выделить заранее.
    Value makeObject(std::uint32_t capacity = 0);

    /// Принять значение туда, что переживёт текущую операцию.
    ///
    /// Единственный переезд во всём движке, и он касается ровно одного случая:
    /// промежуточная строка — смещение в арену операции, а арену граница
    /// сбрасывает. Скаляр и всякая коробка проходят как есть; агрегаты не
    /// копируются нигде и никогда, поэтому ни разделения, ни таблицы
    /// пересылки, ни защиты от циклов здесь больше нет.
    ///
    /// Хранилища-источника в параметрах нет: читать смещение умеет только та
    /// арена, что его выдала, а она во всём выполнении одна. Вычислитель зовёт
    /// это через Execution::promote и хранилища не выбирает.
    [[nodiscard]] Value promote(Value v) {
        if (detail::materialized(v)) { return v; }
        return materialize(string(v));
    }

    // ─── сборка строки по частям ───
    //
    // Нужна format (docs/semantics.md §8.8): длина результата заранее
    // неизвестна, а требовать её вторым проходом значило бы представлять числа
    // дважды. Сборка идёт в собственном буфере build_, отдельном от пула
    // текста text_, а не в самом text_. Причина — не переезд как таковой (с
    // ним переживший переезд срез был бы в порядке), а то, что вычисление
    // очередного куска (аргумент format — строковый литерал, str, вложенный
    // format) само пишет в text_ и не спрашивает разрешения.
    // Если бы сборка велась в text_, чужая запись легла бы прямо между уже
    // собранными кусками и endString забрал бы её как часть результата —
    // сборка не умеет отличить свою запись от чужой, если обе в одном месте.
    // Раздельные хранилища снимают вопрос целиком: что бы ни писало в text_
    // между beginString и endString, build_ этого не видит.
    //
    // Тем же свойством вложенная сборка становится безопасной сама по себе:
    // внутренний format получает мету — позицию в build_ выше меты внешнего,
    // достраивает свой хвост и снимает его целиком через endString раньше,
    // чем внешний допишет следующий кусок. Это стек, а не разделяемый пул, и
    // рекурсивная сборка на этом свойстве и держится.
    //
    // Метка — позиция в build_, а не указатель: как и с любым vector-подобным
    // буфером, рост может переселить данные, и держаться за смещение, а не за
    // адрес, здесь по-прежнему обязательно.

    /// Начинает сборку. Возвращает метку для endString либо abortString.
    std::uint32_t beginString() noexcept;

    /// Дописывает кусок к собираемой строке.
    void appendToString(std::string_view bytes);

    /// Завершает сборку: копирует собранное — всё, что дописано после метки —
    /// в пул текста и возвращает получившуюся строку. Сам build_ усекается
    /// обратно к метке: собранный хвост в нём больше не нужен.
    Value endString(std::uint32_t mark) noexcept;

    /// Отменяет сборку, усекая build_ к метке.
    void abortString(std::uint32_t mark) noexcept;

    /// Освобождает всё разом: пулы усекаются в ноль, ёмкость остаётся. Это и
    /// есть освобождение региона — поштучного здесь нет и не будет
    /// (docs/backlog.md [B57]).
    ///
    /// Сохранённая ёмкость — вся суть: в установившемся режиме следующая
    /// операция укладывается в уже выделенное, и обращений к аллокатору не
    /// остаётся.
    ///
    /// Только для временного региона. Постоянный сбрасывать нечем и незачем.
    /// Всякая строка, выданная этим хранилищем, после вызова недействительна —
    /// она смещение в усечённую арену. Коробки, наоборот, переживут сброс, если
    /// их кто-то удержал: их ссылки уходят через drainPending.
    void clear() noexcept {
        // Утверждение стоит до быстрого пути, а не в clearSlow: там ошибочный
        // вызов на пустом постоянном хранилище прошёл бы молча — сбрасывать
        // нечего, и до проверки дело не доходило.
        assert(region_ != Value::Region::Boxed &&
               "постоянный регион не сбрасывается: на его значения ссылается хост");
        if (text_.empty() && build_.empty()) { return; }
        clearSlow();
    }

    /// Отпускает всё, что накопил список отложенного освобождения.
    ///
    /// Зовёт граница операции (Context::beginOperation), и только она. Коробка,
    /// которую никто не удержал, умирает здесь; удержанная — остаётся.
    ///
    /// Проверка пустоты стоит здесь, в заголовке, а работа — за вызовом.
    /// Причина в замере: `42` подорожало на 30% при том, что памяти не
    /// трогает вовсе, — вся надбавка была двумя невстраиваемыми вызовами на
    /// каждой операции. Пустой список — обычное дело: вычисление, которое
    /// ничего не создало, встречается на кадре чаще всех.
    void drainPending() noexcept { deferred_->drain(); }

    /// Список отложенного освобождения, который ведёт это хранилище.
    [[nodiscard]] Deferred &deferred() noexcept { return *deferred_; }

    /// Таблица имён полей этого хранилища.
    [[nodiscard]] KeyTable *keys() const noexcept { return keys_; }

    // ─── чтение ───

    /// Предусловие: v.kind() == Value::Kind::String.
    std::string_view string(Value v) const noexcept;

    // Чтение агрегата сюда не входит и входить не может: агрегат
    // самодостаточен, и ни один член хранилища при чтении не участвует
    // (core/src/aggregate.hpp).

    // Изменение агрегата сюда не входит по той же причине, что и чтение:
    // мутатору нужен только сам агрегат и список отложенного освобождения
    // (core/src/aggregate.hpp).

    // ─── глобальные переменные ───
    //
    // Раньше таблица глобальных переменных была обычным объектом: имя → значение,
    // и все чтения шли тем же двоичным поиском, что у любого объекта языка.
    // Теперь поиск и хранение разделены.
    //
    // globalNames_ — имя → номер ячейки, отсортирован по имени. Нужен ровно
    // там, где снаружи приходит имя: компиляции (имя стоит в тексте выражения)
    // и записи (имя приходит от хоста). Оба случая разовые.
    //
    // globalValues_ — номер ячейки → значение, только растёт. Ячейки не
    // переезжают, поэтому номер, разрешённый на компиляции, годен навсегда;
    // вставка нового имени двигает записи globalNames_, но номера внутри них
    // едут вместе с именами и не меняются.
    //
    // Ради этого разделения и затевалось: вычисление знает номер из узла дерева
    // и берёт значение индексацией, не трогая ни имени, ни поиска. Замер до
    // правки: чтение переменной 37–45 нс против 9 нс у константы, и вся разница
    // была поиском (docs/benchmarks/).

    /// Значение глобальной переменной либо null, если имени нет.
    Value global(std::string_view name) const noexcept;

    /// Есть ли такое имя. Отличает глобальную переменную со значением null
    /// от отсутствующей.
    bool hasGlobal(std::string_view name) const noexcept;

    /// Номер ячейки по имени либо kNoGlobalSlot, если имени нет.
    ///
    /// Зовёт это check (core/src/check.hpp), раз на узел при компиляции, и
    /// кладёт номер в дерево. Больше номер разрешать негде и незачем.
    [[nodiscard]] GlobalSlot globalSlot(std::string_view name) const noexcept;

    /// Значение по номеру ячейки.
    ///
    /// Предусловие: номер выдан **этим** хранилищем. Выражение, вычисляемое на
    /// чужом контексте, прочитало бы чужую ячейку молча, поэтому в отладочной
    /// сборке несовпадение ловится утверждением — как и отметка прохода check
    /// в eval.
    [[nodiscard]] Value globalValueAt(GlobalSlot slot) const noexcept;

    /// Заводит глобальную переменную либо заменяет значение существующей.
    /// Имя не проверяется: требование «всякая глобальная переменная адресуема
    /// идентификатором» держится на вызывающем, и единственный такой
    /// вызывающий — setVariable из data.hpp.
    void setGlobal(std::string_view name, Value v);

    std::uint32_t globalCount() const noexcept;

    /// Имя глобальной переменной по порядковому номеру **в алфавитном порядке
    /// имён**, а не по номеру ячейки; пустой срез за границей.
    std::string_view globalNameAt(std::uint32_t i) const noexcept;

    // ─── метрики ───

    /// Сколько байт занято выданными данными. Черновик сборки build_ сюда не
    /// входит: пока endString не скопировал его в text_, это ничей черновик, а
    /// не выданные данные — на него не указывает ни одно Value.
    std::size_t bytesUsed() const noexcept;
    /// Сколько байт занято у аллокатора, включая запас пулов — в том числе
    /// build_: endString возвращает его к нулевой длине, но не к нулевой
    /// ёмкости, и эта ёмкость — тот же самый резерв, что и у прочих пулов.
    std::size_t bytesReserved() const noexcept;

   private:
    const Value::Region region_;

    /// Собственно сброс арены. Отделён от проверки, чтобы та встраивалась.
    void clearSlow() noexcept;

    std::uint32_t appendText(std::string_view bytes);
    std::string_view textAt(std::uint32_t offset, std::uint32_t length) const noexcept;

    std::uint32_t findGlobal(std::string_view name, bool *found) const noexcept;


    // ─── байты: выданные отдельно от черновика ───
    //
    // text_ — единственное адресное пространство строк: Value вида String это
    // пара «смещение, длина» в нём и ничего другого означать не может. Сюда
    // попадает всё, на что такой Value указывает, и всё, на что указывает
    // Entry либо GlobalName: содержимое строковых литералов, результат str и
    // format, ключи объектов, имена глобальных переменных. Только дописывание;
    // усечения нет, поэтому равные строки лежат столькими копиями, сколько раз
    // их создали (docs/backlog.md B1, B51).
    //
    // build_ — черновик format и только он. Отдельный от text_ потому, что
    // вычисление очередного аргумента само пишет в text_ и легло бы прямо
    // между уже собранными кусками; развёрнуто это разобрано выше, у
    // beginString. endString переносит собранное в text_ и усекает build_
    // обратно к метке.
    std::vector<char> text_;   // байты промежуточных строк и имён глобальных
    std::string build_;        // черновик сборки format

    /// Таблица имён, которую хранилище выдаёт **создаваемым** объектам.
    /// Чтение чужого объекта на неё не смотрит — тот носит свою.
    ///
    /// Удерживается ссылкой: её переживает всякий объект, уехавший к хосту,
    /// поэтому умереть вместе с хранилищем она не вправе.
    KeyTable *keys_;

    /// Отложенное освобождение (core/src/deferred.hpp). Своё, если хранилище
    /// заведено само по себе, и общее с постоянным, если это арена операции.
    Deferred owned_;
    Deferred *deferred_;

    // ─── оснастка: литералы единиц ───
    //
    // Коробки строковых литералов, уложенные компиляцией. Держатся здесь, а не в
    // списке отложенного освобождения: литерал не мусор одной операции, он
    // часть программы и обязан дожить до смерти хранилища — на него смотрит
    // дерево разбора, а не значение.
    std::vector<detail::StringBox *> literals_;

    // ─── глобальные переменные: поиск отдельно от хранения ───
    //
    // globalNames_ отсортирован по имени и читается только там, где имя
    // приходит снаружи: на компиляции (check разрешает имя в номер ячейки и
    // кладёт номер в узел дерева) и на записи от хоста. Вычисление сюда не
    // ходит вовсе — оно берёт значение индексацией globalValues_ по номеру из
    // узла.
    //
    // Значение лежит в ячейке, а не в записи имени, именно ради этого: вставка
    // нового имени сдвигает записи, чтобы сохранить сортировку, и значение
    // сдвинулось бы вместе с записью, обесценив номер, разрешённый на
    // компиляции. globalValues_ только растёт, ячейки не переезжают.
    //
    // Первый setGlobal("width", 320) заводит ячейку 0 со значением 320 и
    // запись {смещение байт `width` в text_, 5, 0}. Повторный setGlobal того же
    // имени перезаписывает globalValues_[0] и в globalNames_ не пишет ничего.
    // setGlobal("alpha", …) добавляет ячейку 1, но её запись встаёт в таблице
    // имён перед `width`: номер ячейки от места в таблице не зависит.
    std::vector<detail::GlobalName> globalNames_;  // имя → номер ячейки
    std::vector<Value> globalValues_;              // номер ячейки → значение
};

}  // namespace CS
