#pragma once
#include <vector>

#include "box.hpp"
#include "value.hpp"

namespace CS {

/// Отложенное освобождение: ссылки, которые надо отпустить на ближайшей
/// границе операции.
///
/// Сюда попадает ссылка новорождённой коробки и всякая вытесненная ссылка —
/// перезаписанная ячейка, снятый pop, заменённое значение глобальной
/// переменной. Освобождать вытесненное на месте нельзя: вычислитель держит
/// прочитанные значения голым Value без всякого RAII, и `x = a.pop()` уронил
/// бы счётчик в ноль ровно между чтением и записью.
///
/// Корнем список не является: он держит ссылку до ближайшего слива, а не до
/// смерти контекста. Держи он до смерти — корнем стало бы всё созданное, и
/// освобождать было бы нечего, а весь смысл счётчика в том, чтобы не держать
/// ненужное.
///
/// Список один на операцию, а не по одному на хранилище. Раньше их было два —
/// у арены и у постоянного, — и какой из них примет ссылку, решал регион
/// значения. Решение это ни на что не влияло: сливались оба в одной и той же
/// границе операции, разом. Два списка делали работу одного и стоили лишнего
/// вызова на каждом вычислении.
///
/// Обоснование:
/// docs/superpowers/specs/2026-08-19-memory-model-redesign-design.md Р3.
class Deferred {
   public:
    Deferred() = default;
    ~Deferred() { drain(); }

    Deferred(const Deferred &) = delete;
    Deferred &operator=(const Deferred &) = delete;

    /// Отдать ссылку значения, если оно ею владеет.
    void take(Value v) {
        if (detail::Box *box = detail::boxOf(v)) { refs_.push_back(box); }
    }

    /// Отдать ссылку новорождённой коробки — ту, что принадлежит создателю.
    void take(detail::Box *box) { refs_.push_back(box); }

    /// Отпускает всё накопленное.
    ///
    /// Проверка пустоты стоит здесь, а работа — за вызовом. Причина в замере:
    /// `42` подорожало на 30% при том, что памяти не трогает вовсе, — вся
    /// надбавка была невстраиваемым вызовом на каждой операции. Пустой список
    /// — обычное дело: вычисление, которое ничего не создало, встречается на
    /// кадре чаще всех.
    void drain() noexcept {
        if (refs_.empty()) { return; }
        drainSlow();
    }

   private:
    void drainSlow() noexcept;

    std::vector<detail::Box *> refs_;
};

}  // namespace CS
