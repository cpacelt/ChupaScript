/// Построение `String` из байт, которые заведомо являются корректным UTF-8.
///
/// `String(decoding:as: UTF8.self)` — три четверти цены чтения длинной строки
/// на границе с движком (`docs/backlog.md` B49), и это не аллокация и не
/// копирование, а проверка кодировки. `validateUTF8`
/// (`stdlib/public/core/StringUTF8Validation.swift`) начинается с векторного
/// `_allASCII`, а при первом же не-ASCII байте уходит в скалярный цикл через
/// итератор с вложенными замыканиями. Контент BDUI русский, то есть быстрая
/// половина недостижима в принципе. Замер на 539 байтах кириллицы:
///
/// | | нс |
/// |---|---|
/// | `String(decoding:)` | 278.4 |
/// | путь ниже | 44.9 |
///
/// Оставшиеся ~45 нс — аллокация и `memcpy`, тот минимум, ниже которого
/// владеющая строка не бывает. На ASCII разницы почти нет (48.8 против 43.6):
/// там валидации и так не было.
///
/// **Почему подчёркнутый символ, а не публичный API.** Пропустить проверку
/// публично позволяет `String.init(copying: UTF8Span)` из SE-0464, но он помечен
/// `@available(SwiftStdlib 6.2, *)`, то есть iOS 26, а цель развёртывания у
/// пакета — iOS 15.6 (`Package.swift`). Где он есть — он и берётся: обёртка
/// ниже спрашивает про него через `#available` и к подчёркнутому символу на
/// iOS 26 не обращается вовсе. Ниже этой планки безопасного публичного способа
/// нет, и это не догадка: мотивационная часть SE-0464 сама пишет, что без
/// валидации строку можно построить «only theoretically possible via a custom
/// NSString subclass». Этот путь измерен в лоб — `NSString(bytes:)` даёт 1335 нс,
/// впятеро хуже исходного. `String.init(unsafeUninitializedCapacity:)` тоже не
/// годится: он валидирует **после** заполнения
/// (`_fromLargeUTF8Repairing`), то есть та же проверка плюс лишний проход.
///
/// **Чем этот символ надёжен.** `_uncheckedFromUTF8(_:isASCII:)` помечен
/// `@usableFromInline` начиная со swift-5.0-RELEASE, то есть экспортирован в ABI
/// с момента его стабилизации, и сигнатура не менялась с 5.0 по 6.2. Сломаться
/// от обновления Xcode он не может — ABI зафиксирован.
///
/// **Чем ненадёжен.** Имя подчёркнутое, то есть ничем не обещано. Если символ
/// когда-нибудь исчезнет, это будет падение при загрузке образа, а не ошибка
/// компиляции. Риск ограничен временем: на iOS 26 и выше берётся публичный
/// путь, так что до символа доходят только старые системы, где стандартная
/// библиотека вкомпилирована в саму ОС и меняться уже не может. Когда цель
/// развёртывания дорастёт до iOS 26, весь этот файл сводится к одной строке
/// `String(copying: UTF8Span(unchecked:))`.
///
/// Компилятор старше 6.2 про `UTF8Span` не знает, поэтому публичная ветка ещё
/// и под `#if compiler(>=6.2)`: на таком компиляторе `#available` всё равно
/// никогда бы не сработал.
extension String {

    /// Пропускает проверку кодировки. Байты обязаны быть корректным UTF-8 —
    /// см. `chupaFromValidUTF8` ниже, где это условие разобрано.
    @_silgen_name("$sSS18_uncheckedFromUTF8_7isASCIISSSRys5UInt8VG_SbtFZ")
    internal static func _uncheckedFromUTF8(
        _ input: UnsafeBufferPointer<UInt8>, isASCII: Bool) -> String

    /// Строит строку из байт движка, не проверяя кодировку.
    ///
    /// **Предусловие: байты — корректный UTF-8.** Внутри обёртки оно держится
    /// целиком: строки приходят либо от хоста через `Context`, который берёт их
    /// из `String.utf8`, либо из литералов исходника, который сам пришёл из
    /// `String`. Внутри движка байты только склеиваются; единственная резка — в
    /// `format`, и она идёт по маркерам `$`, `{`, `}`, то есть по ASCII-границам,
    /// разорвать скаляр не может. Агрегат в строку не превращается —
    /// `str` и `format` его отвергают.
    ///
    /// Для хоста, который зовёт C API напрямую, минуя эту обёртку, условие
    /// становится его обязанностью, и записано оно в `chupascript.h`.
    ///
    /// Нарушение предусловия — не порча текста, а неопределённое поведение:
    /// прежний `String(decoding:)` негодную последовательность заменял на
    /// U+FFFD и показывал испорченный контент испорченным, здесь такой замены
    /// не происходит.
    ///
    /// `isASCII` передаётся `false` всегда, и вычислять его незачем: флаг
    /// выбирает представление, а не смысл, и заниженное значение лишь уводит
    /// последующие операции с более быстрого пути на общий. Завышенное было бы
    /// ошибкой, заниженное — нет. Совпадение результата с `String(decoding:)`
    /// по равенству, длине, скалярам, хэшу и порядку проверено тестами на
    /// пустой, короткой, длинной, ASCII, кириллической строке и на эмодзи.
    internal static func chupaFromValidUTF8(
        _ bytes: UnsafePointer<CChar>?, count: Int) -> String {
        // Пустой результат приходит и с нулевым указателем: у пустой строки
        // движку нечего показать в пуле текста. UnsafeBufferPointer с nil
        // допустим только при нулевой длине, а заводить его ради пустой строки
        // незачем вовсе.
        guard let bytes, count > 0 else { return "" }
        return bytes.withMemoryRebound(to: UInt8.self, capacity: count) { start in
            let buffer = UnsafeBufferPointer(start: start, count: count)
            // Публичный путь берётся, как только он доступен, — тогда
            // подчёркнутый символ не задействован вовсе. Проверка версии
            // сравнивает закэшированную версию системы с константой; на фоне
            // аллокации и memcpy ниже это ничто.
            #if compiler(>=6.2)
            if #available(macOS 26, iOS 26, tvOS 26, watchOS 26, visionOS 26, *) {
                return String(copying: UTF8Span(unchecked: buffer.span))
            }
            #endif
            return String._uncheckedFromUTF8(buffer, isASCII: false)
        }
    }
}
