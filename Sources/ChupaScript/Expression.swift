import ChupaScriptC

/// Скомпилированное выражение, обещающее результат типа `T`.
///
/// Владеет своим C-хэндлом и освобождает его в `deinit`; контекст этого не
/// делает.
///
/// **Контекст живёт не меньше выражения.** Ссылка на него сильная, поэтому
/// через Swift контекст раньше своих выражений не умрёт. C API это разрешает —
/// хэндл выражения контекст не удерживает и может его пережить, — но обвязка
/// такой порядок не предоставляет намеренно: вычислять выражение без живого
/// контекста всё равно нельзя, а один сильный указатель дешевле, чем правило,
/// которое хост обязан соблюдать сам.
///
/// **Параметр `T` намеренно ничем не ограничен.** Ограничение живёт на
/// расширении ниже, а не на классе. Так `Expression` остаётся типом, который
/// можно назвать где угодно — в поле, в сигнатуре, в словаре, — не доказывая
/// при этом, что результат вычислим. Вычислять умеет тот, кто подписан на
/// `CSValue`; хранить и передавать — кто угодно.
///
///     enum Align: String, CSValue { case left, right }
///
/// Обёртке довольно одного слова: тело разбора приезжает из умолчания на
/// `CSValue`. Раньше и слова не требовалось, но та конструкция ломалась от
/// чужого ретроактивного конформанса — см. `CSValue`.
///
/// **Чем `T` является и чем не является.** На компиляции движок типы не
/// проверяет: статический проход смотрит имена, арность и плейсхолдеры, но не
/// типы. Зато проверяет на каждом вычислении — при несовпадении возвращает
/// ошибку с кодом `.type`. Так что `T` — не пустое обещание, а утверждение с
/// поздней проверкой: неверно объявленный тип даёт внятную ошибку вместо
/// тихого `nil`.
public final class Expression<T> {

    internal let handle: OpaquePointer
    internal let context: Context

    internal init(handle: OpaquePointer, context: Context) {
        self.handle = handle
        self.context = context
    }

    deinit {
        chupa_expression_destroy(handle)
    }
}

// MARK: - Вычисление

extension Expression where T: CSValue {

    /// Вычислить выражение.
    ///
    /// `nil` — язык дал `null`. Это штатный исход, а не сбой: чтение
    /// отсутствующего ключа мягкое (`docs/semantics.md` §6.3).
    ///
    /// Бросает `Error`, если движок сообщил об ошибке, — в том числе с кодом
    /// `.type`, когда выражение дало не тот тип, который обещает `T`. Для
    /// обёрток добавляется `.unrepresentable`: сырьё корректно, но `T` из него
    /// не собирается (`CSValue.chupaEval`).
    ///
    /// **Объявление одно намеренно.** Прежде их было два — это же плюс близнец
    /// для `T: RawRepresentable`, — и одинаковые сигнатуры сделали вызов
    /// невозможным в хосте, где чужой модуль объявил `String`
    /// `RawRepresentable`. Разбор обёрток живёт умолчанием на `CSValue`, а не
    /// второй перегрузкой; подробности там же.
    public func eval() throws -> T? {
        try T.chupaEval(from: self)
    }

    /// Вычислить, ничего не бросая.
    ///
    /// Для горячего пути: выражение пересчитывается на каждую перерисовку, и
    /// бросок на каждый кадр никому не нужен. `null` и ошибка одинаково дают
    /// `fallback`.
    ///
    /// Причину при этом можно узнать — но только сразу: `context.error`
    /// сбрасывается перед каждой следующей операцией над контекстом, включая
    /// успешную. Логировать надо прямо после вызова, а не в конце кадра.
    public func eval(default fallback: T) -> T {
        (try? eval()) ?? fallback
    }
}
