#pragma once
#include <string_view>

#include "ast.hpp"
#include "diagnostic.hpp"
#include "execution.hpp"
#include "store.hpp"
#include "value.hpp"

namespace CS {

/// Вычисляет разобранное выражение и кладёт результат в *out.
///
/// Дерево обязано быть построено compileExpression (core/src/compile.hpp)
/// успешно — то есть разобрано **и** проверено статическим проходом
/// (core/src/check.hpp): у неудачного разбора корень равен kNoNode, а без
/// отметки check вычислять дерево нельзя, и то и другое утверждается. source
/// обязан быть тем же текстом, над которым дерево построено: имена и
/// содержимое литералов дерево хранит смещениями в нём.
///
/// exec — состояние выполнения (core/src/execution.hpp): всё изменяемое, что
/// принадлежит вычислению, а не программе. Владеет им вызывающий, и оно
/// переживает вызов. Сегодня вычислитель его не читает: временный регион
/// заводится, но значения по-прежнему создаются в store — параметр появился
/// раньше содержимого, чтобы перенос не переписывал сигнатуры (docs/backlog.md
/// [B57], порядок работ, пункты 2 и 5).
///
/// Значения-агрегаты создаются в store и живут по его правилам. При отказе
/// возвращает false и заполняет diag; смещение считается от начала исходника
/// выражения. При отказе *out не трогается — на это соглашение опираются ??
/// и тернарный, передающие out вызывающего прямо во внутреннюю рекурсию.
bool evalExpression(const Ast &ast, std::string_view source, Store &store,
                    Execution &exec, Value *out, Diagnostic &diag);

/// Выполняет разобранный скрипт: последовательность стейтментов.
///
/// Дерево обязано быть построено compileScript (core/src/compile.hpp)
/// **успешно** — то есть разобрано и проверено статическим проходом: у
/// неудачного разбора корень равен kNoNode, а без отметки check выполнять
/// дерево нельзя, и то и другое утверждается. source обязан быть тем же
/// текстом, над которым дерево построено: имена и содержимое литералов
/// дерево хранит смещениями в нём.
///
/// exec — как у evalExpression выше.
///
/// Значения нет: результат это признак успеха (docs/semantics.md §3.1). Ошибка
/// прерывает выполнение посередине, и сделанное остаётся сделанным — откатывать
/// нечего, предыдущих состояний хранилище не держит.
bool runScript(const Ast &ast, std::string_view source, Store &store,
               Execution &exec, Diagnostic &diag);

}  // namespace CS
