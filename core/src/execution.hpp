#pragma once
#include "store.hpp"
#include "value.hpp"

namespace CS {

/// Всё изменяемое, что нужно одному выполнению и не принадлежит программе.
///
/// Вынесено из единицы, а не сложено в неё, чтобы одну скомпилированную
/// единицу можно было разделять между вьюшками ([B4], [B28]): изменяемое
/// состояние внутри неё запрещало бы и разделение, и вложенное выполнение
/// той же единицы. Владеет им вызывающий — сегодня контекст C API. Ячейки
/// локальных и начало активационной записи придут с объявлениями
/// (docs/backlog.md [B57]).
///
/// Живёт дольше одного вычисления намеренно: временный регион сбрасывается с
/// сохранением ёмкости, и в установившемся режиме обращений к аллокатору не
/// остаётся. Экземпляр на вызов эту ёмкость терял бы каждый раз.
struct Execution {
    /// Временный регион: значения, созданные вычислением. Пока не читается
    /// никем — значения по-прежнему создаются в постоянном хранилище; перенос
    /// это пункт 5 порядка работ [B57].
    Store scratch{Value::Region::Scratch};
};

/// Хранилище, которому принадлежит значение: читать агрегат и строку может
/// только оно, потому что значение это индекс в его пулы.
///
/// Выбор по региону — единственный доступный: личности хранилища в Value нет,
/// только категория ([B57]). Отсюда граница применимости: два временных
/// хранилища эта функция не различит, и если их когда-нибудь окажется больше
/// одного на выполнение, выбирать придётся иначе.
///
/// У скаляра региона нет, поле у него равно постоянному по умолчанию, и
/// функция вернёт постоянное хранилище. Это безвредно: у скаляра нечего
/// читать, в пулы он не смотрит.
[[nodiscard]] inline const Store &storeOf(const Store &persistent,
                                          const Execution &exec,
                                          Value v) noexcept {
    return v.region() == Value::Region::Scratch ? exec.scratch : persistent;
}

[[nodiscard]] inline Store &storeOf(Store &persistent, Execution &exec,
                                    Value v) noexcept {
    return v.region() == Value::Region::Scratch ? exec.scratch : persistent;
}

}  // namespace CS
